static void hero_beaver(int x,int y,int dir,int pose){
 hero_tint=1;beaver(x,y,dir,pose,0);hero_tint=0;if(pose<0||pose>=BEAVER_ANIM_COUNT)pose=BA_IDLE;
 int origin=x-(dir>0?22:7),top=game.dead?beaver_pose_top(pose):0;
 for(int i=0;i<HEADBAND_POINTS;i++){
  int sx=headband_xy[pose][i][0],sy=headband_xy[pose][i][1],at=sy*BEAVER_ANIM_W+sx;
  int p=beaver_anim[pose][at/2];p=(at&1)?p&15:p>>4;
  /* Never paint transparency, the dark eye, or the lower muzzle. */
  if(p&&p<14)cv_pset(origin+(dir>0?sx:BEAVER_ANIM_W-1-sx),y+(game.dead?31+top-sy:player_crouched()?8+(sy*24+31)/32:sy),RGB(228,41,45));
 }
}
